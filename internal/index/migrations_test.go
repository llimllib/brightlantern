func fmtInts(xs []int) string {
	s := "["
	for i, x := range xs {
		if i > 0 {
			s += " "
		}
		s += strconv.Itoa(x)
	}
	return s + "]"
}

// An index from a released binary merges as it is: it records no migrations,
// which is what it has.
func TestReleasedIndexMerges(t *testing.T) {
	db := openTest(t)
	p, err := Merge(context.Background(), db, copyFixture(t, "v0.0.1.db"), MergeOptions{})
	if err != nil {
		t.Fatalf("merging v0.0.1's index: %v", err)
	}
	if got := count(t, db.SQL(), `SELECT COUNT(*) FROM messages`); got != 48 {
		t.Errorf("merged %d messages, want 48 (%+v)", got, p)
	}
}
